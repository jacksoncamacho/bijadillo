export const FX: Record<string, number> = { COP: 1, USD: 1 / 4200, EUR: 1 / 4500 }
export const CURRENCY_SYMBOL: Record<string, string> = { COP: "$", USD: "US$", EUR: "€" }
export const CURRENCY_LOCALE: Record<string, string> = { COP: "es-CO", USD: "en-US", EUR: "fr-FR" }

export function formatPrice(copAmount: number, currency: string = "COP"): string {
  const rate = FX[currency] || 1
  const value = copAmount * rate
  if (currency === "COP") return CURRENCY_SYMBOL.COP + Math.round(value).toLocaleString(CURRENCY_LOCALE.COP) + " COP"
  return CURRENCY_SYMBOL[currency] + value.toLocaleString(CURRENCY_LOCALE[currency], { minimumFractionDigits: 2, maximumFractionDigits: 2 })
}

